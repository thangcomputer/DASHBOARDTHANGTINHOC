/**
 * One-off: extract Vietnam mainland from Natural Earth 110m → shared/dailyPractice/vietnamMapGeo.mjs
 * Source: ne_110m_admin_0_countries.geojson (Public Domain)
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const geoPath = path.join(root, 'shared/dailyPractice/_ne110.geojson');
const outPath = path.join(root, 'shared/dailyPractice/vietnamMapGeo.mjs');

const geo = JSON.parse(fs.readFileSync(geoPath, 'utf8'));
const vn = geo.features.find((f) => {
  const p = f.properties || {};
  return p.ISO_A3 === 'VNM' || p.ADM0_A3 === 'VNM' || String(p.NAME).includes('Vietnam');
});
if (!vn) throw new Error('Vietnam feature not found in GeoJSON');

const rings = [];
const pushCoords = (coords) => {
  for (const ring of coords) {
    rings.push(ring);
  }
};
if (vn.geometry.type === 'Polygon') pushCoords(vn.geometry.coordinates);
else if (vn.geometry.type === 'MultiPolygon') {
  for (const poly of vn.geometry.coordinates) pushCoords(poly);
}

let minLon = Infinity;
let maxLon = -Infinity;
let minLat = Infinity;
let maxLat = -Infinity;
for (const ring of rings) {
  for (const [lon, lat] of ring) {
    minLon = Math.min(minLon, lon);
    maxLon = Math.max(maxLon, lon);
    minLat = Math.min(minLat, lat);
    maxLat = Math.max(maxLat, lat);
  }
}

const W = 220;
const H = 480;
const pad = 8;
const project = ([lon, lat]) => {
  const x = pad + ((lon - minLon) / (maxLon - minLon || 1)) * (W - pad * 2);
  const y = pad + (1 - (lat - minLat) / (maxLat - minLat || 1)) * (H - pad * 2);
  return [Number(x.toFixed(2)), Number(y.toFixed(2))];
};

function ringToPath(ring) {
  if (!ring.length) return '';
  const [x0, y0] = project(ring[0]);
  let d = `M${x0} ${y0}`;
  for (let i = 1; i < ring.length; i += 1) {
    const [x, y] = project(ring[i]);
    d += ` L${x} ${y}`;
  }
  return `${d} Z`;
}

const mainlandPath = rings
  .filter((ring) => ring.length > 40)
  .sort((a, b) => b.length - a.length)
  .slice(0, 1)
  .map(ringToPath)
  .join(' ');

const allProjected = rings.flat().map(project);
const midY = (minLat + maxLat) / 2;
const northCut = minLat + (maxLat - minLat) * 0.36;
const southCut = minLat + (maxLat - minLat) * 0.68;

const spine = [];
for (let t = 0.05; t <= 0.95; t += 0.08) {
  const lat = minLat + (maxLat - minLat) * t;
  const pts = rings.flat().filter(([, la]) => Math.abs(la - lat) < 0.35);
  if (!pts.length) continue;
  const lon = pts.reduce((s, p) => s + p[0], 0) / pts.length;
  spine.push(project([lon, lat]));
}

const journeyD = spine.length
  ? spine.map(([x, y], i) => `${i === 0 ? 'M' : 'L'}${x} ${y}`).join(' ')
  : '';

const file = `/**
 * Vietnam mainland outline (Natural Earth 110m Admin 0 — Public Domain).
 * Generated by scripts/gen-vietnam-map-svg.mjs — do not hand-edit path data.
 */
export const VIETNAM_MAP_VIEWBOX = '0 0 ${W} ${H}';

/** Single merged mainland path (largest polygon, simplified at source scale). */
export const VIETNAM_MAINLAND_PATH = ${JSON.stringify(mainlandPath)};

/** Latitude cutoffs in source WGS84 for tri-band progress (Bắc / Trung / Nam). */
export const VIETNAM_BAND_LAT = {
  northMax: ${northCut.toFixed(4)},
  centralMax: ${southCut.toFixed(4)},
};

/** Decorative journey spine in map coordinates (not a border). */
export const VIETNAM_JOURNEY_SPINE = ${JSON.stringify(journeyD)};
`;

fs.writeFileSync(outPath, file, 'utf8');
console.log('Wrote', outPath, 'spine points:', spine.length);
